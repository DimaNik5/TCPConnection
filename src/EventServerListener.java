/**
 * Интерфейс слушателя событий сервера.
 * Определяет callback-методы для обработки событий жизненного цикла сервера
 * и взаимодействия с клиентскими подключениями.
 */
public interface EventServerListener {

    /**
     * Вызывается при успешном подключении нового клиента.
     * Может использоваться для обновления статистики подключений
     * или уведомления администратора.
     */
    void onConnectionReady();

    /**
     * Вызывается при получении сообщения от любого из подключенных клиентов.
     * @param value текст полученного сообщения в кодировке UTF-8,
     *              не должен быть null (пустые сообщения приходят как "")
     */
    void onReceiveString(String value);

    /**
     * Вызывается при отключении клиента.
     * Может использоваться для очистки ресурсов, связанных с клиентом,
     * или логирования события отключения.
     */
    void onDisconnect();

    /**
     * Вызывается при возникновении критической ошибки в работе сервера.
     * @param e исключение, содержащее информацию об ошибке.
     *          Типичные случаи: IOException - сетевые ошибки,
     *          SecurityException - проблемы с правами доступа.
     */
    void onException(Exception e);

    /**
     * Устанавливает IP-адрес сервера для внешнего использования.
     * Вызывается один раз при старте сервера.
     * @param ip строковое представление IP-адреса сервера
     *           в формате "xxx.xxx.xxx.xxx".
     *           Не может быть null или пустой строкой.
     */
    void setIP(String ip);
}