/**
 * Интерфейс слушателя событий клиентского приложения.
 * Определяет методы обратного вызова для обработки событий, связанных с работой клиента.
 */
public interface EventClientListener {

    /**
     * Вызывается при успешном установлении соединения с сервером.
     * Может использоваться для обновления UI или выполнения других действий
     * при готовности соединения.
     */
    void onConnectionReady();

    /**
     * Вызывается при получении нового сообщения от сервера.
     * @param value полученное текстовое сообщение, может быть null 
     *              если соединение было разорвано
     */
    void onReceiveString(String value);

    /**
     * Вызывается при разрыве соединения с сервером.
     * Может использоваться для очистки ресурсов, уведомления пользователя
     * или попытки переподключения.
     */
    void onDisconnect();

    /**
     * Вызывается при возникновении исключения в работе клиента.
     * @param e исключение, содержащее информацию об ошибке.
     *          Может быть IOException при проблемах с сетью или
     *          другими исключениями, связанными с работой соединения.
     */
    void onException(Exception e);
}